"""Write a PIL RGB image as an LVGL RGB565 lv_image_dsc_t C file."""


def write_rgb565_c(im, name, path, generator):
    w, h = im.size
    data = []
    for r, g, b in im.convert("RGB").getdata():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += [v & 0xFF, v >> 8]
    rows = [", ".join(f"0x{x:02x}" for x in data[i:i + 19]) for i in range(0, len(data), 19)]
    with open(path, "w") as f:
        f.write(f"/* Generated by tools/{generator} */\n#include <lvgl.h>\n\n")
        f.write(f"static const uint8_t {name}_map[] = {{\n    " + ",\n    ".join(rows) + ",\n};\n\n")
        f.write(f"const lv_image_dsc_t {name} = {{\n"
                "    .header.cf    = LV_COLOR_FORMAT_RGB565,\n"
                "    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
                f"    .header.w     = {w},\n    .header.h     = {h},\n"
                f"    .data_size    = {w * h} * 2,\n    .data         = {name}_map,\n}};\n")
